from __future__ import annotations

from typing import Protocol

from .domain import BookTop, QuoteLeg


class MarketDataPort(Protocol):
    async def subscribe(self, symbols: tuple[str, ...]) -> None: ...
    async def next_book(self) -> BookTop: ...
    async def resync(self, symbol: str) -> None: ...


class AccountStatePort(Protocol):
    async def subscribe_account(self) -> None: ...
    async def reconcile(self) -> None: ...


class ExecutionPort(Protocol):
    async def place_maker(self, leg: QuoteLeg) -> str: ...
    async def cancel(self, order_id: str) -> None: ...
    async def cancel_all(self) -> None: ...


class MetadataPort(Protocol):
    async def refresh_reward_catalog(self) -> None: ...

